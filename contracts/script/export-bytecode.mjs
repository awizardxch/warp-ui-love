// Writes the compiled WrappedStock creation bytecode into the web app, so the
// deploy page can deploy it from a browser wallet.
//
// Run from the repo root after `forge build` in contracts/:
//   node contracts/script/export-bytecode.mjs
//   node contracts/script/export-bytecode.mjs --check   (fail if out of date)
//
// The output is committed. Re-run this whenever WrappedStock.sol changes.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const artifactPath = join(here, "..", "out", "WrappedStock.sol", "WrappedStock.json");
const outPath = join(here, "..", "..", "src", "app", "bridge", "drivers", "wrappedStockBytecode.ts");

const artifact = JSON.parse(readFileSync(artifactPath, "utf8"));
const bytecode = artifact.bytecode.object;
if (!/^0x[0-9a-f]+$/i.test(bytecode)) {
  throw new Error("Unexpected bytecode in the artifact. Run `forge build` first.");
}

const content = `// GENERATED by contracts/script/export-bytecode.mjs from contracts/src/WrappedStock.sol.
// Do not edit by hand. Compiler settings are in contracts/foundry.toml.

export const WrappedStockConstructorABI = [
  {
    type: "constructor",
    stateMutability: "nonpayable",
    inputs: [
      { name: "underlying_", type: "address" },
      { name: "name_", type: "string" },
      { name: "symbol_", type: "string" },
      { name: "decimals_", type: "uint8" },
    ],
  },
] as const;

export const WRAPPED_STOCK_BYTECODE = "${bytecode}" as const;
`;

if (process.argv.includes("--check")) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== content) {
    console.error("wrappedStockBytecode.ts is out of date. Run: node contracts/script/export-bytecode.mjs");
    process.exit(1);
  }
  console.log("wrappedStockBytecode.ts matches the compiled contract.");
} else {
  writeFileSync(outPath, content);
  console.log(`Wrote ${outPath} (${(bytecode.length - 2) / 2} bytes of creation code).`);
}
