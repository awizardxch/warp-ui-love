// Writes the compiled creation bytecode of WrappedStock and StockBridgeRouter
// into the web app, so the deploy page can deploy them from a browser wallet.
//
// Run from the repo root after `forge build` in contracts/:
//   node contracts/script/export-bytecode.mjs
//   node contracts/script/export-bytecode.mjs --check   (fail if out of date)
//
// The output is committed. Re-run this whenever either contract changes.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { keccak256 } from "ethers";

const here = dirname(fileURLToPath(import.meta.url));
const outPath = join(here, "..", "..", "src", "app", "bridge", "drivers", "wrappedStockBytecode.ts");

function creationCode(name, file = name) {
  const artifact = JSON.parse(readFileSync(join(here, "..", "out", `${file}.sol`, `${name}.json`), "utf8"));
  const bytecode = artifact.bytecode.object;
  if (!/^0x[0-9a-f]+$/i.test(bytecode)) {
    throw new Error(`Unexpected bytecode for ${name}. Run \`forge build\` first.`);
  }
  return bytecode;
}

const wrappedStock = creationCode("WrappedStock");
const router = creationCode("StockBridgeRouter");
// The router deploys each user's forwarder with CREATE2 from this exact code.
const forwarderInitCodeHash = keccak256(creationCode("UnwrapForwarder", "StockBridgeRouter"));

const content = `// GENERATED by contracts/script/export-bytecode.mjs from contracts/src/.
// Do not edit by hand. Compiler settings are in contracts/foundry.toml.

export const WrappedStockConstructorABI = [
  {
    type: "constructor",
    stateMutability: "nonpayable",
    inputs: [
      { name: "underlying_", type: "address" },
      { name: "name_", type: "string" },
      { name: "symbol_", type: "string" },
    ],
  },
] as const;

export const WRAPPED_STOCK_BYTECODE = "${wrappedStock}" as const;

export const StockBridgeRouterConstructorABI = [
  {
    type: "constructor",
    stateMutability: "nonpayable",
    inputs: [
      { name: "bridge_", type: "address" },
      { name: "portal_", type: "address" },
    ],
  },
] as const;

export const STOCK_BRIDGE_ROUTER_BYTECODE = "${router}" as const;

// keccak256 of the UnwrapForwarder creation code. With the router address and a
// user address it gives that user's forwarder address (CREATE2), so the site can
// check the router's answer instead of trusting a single RPC response.
export const UNWRAP_FORWARDER_INIT_CODE_HASH = "${forwarderInitCodeHash}" as const;
`;

if (process.argv.includes("--check")) {
  const current = existsSync(outPath) ? readFileSync(outPath, "utf8").replace(/\r\n/g, "\n") : "";
  if (current !== content) {
    console.error("wrappedStockBytecode.ts is out of date. Run: node contracts/script/export-bytecode.mjs");
    process.exit(1);
  }
  console.log("wrappedStockBytecode.ts matches the compiled contracts.");
} else {
  writeFileSync(outPath, content);
  console.log(`Wrote ${outPath}`);
  console.log(`  WrappedStock ${(wrappedStock.length - 2) / 2} bytes, StockBridgeRouter ${(router.length - 2) / 2} bytes of creation code.`);
}
